// ── Helper Functions ──────────────────────────────────────────────────────────

/**
 * Get a random message from a given category
 */
export const getRandomMessage = (category) => {
  const messages = mentorMessages[category];
  if (!messages) return '';
  if (Array.isArray(messages)) {
    return messages[Math.floor(Math.random() * messages.length)];
  }
  return '';
};

/**
 * Get a greeting based on time of day
 */
export const getTimeBasedGreeting = () => {
  const hour = new Date().getHours();
  let period;
  if (hour < 6) period = 'night';
  else if (hour < 9) period = 'earlyMorning';
  else if (hour < 12) period = 'morning';
  else if (hour < 17) period = 'afternoon';
  else if (hour < 21) period = 'evening';
  else period = 'night';

  const msgs = mentorMessages.timeOfDay[period];
  return msgs[Math.floor(Math.random() * msgs.length)];
};

/**
 * Get streak message for a given streak count
 */
export const getStreakMessage = (days) => {
  const thresholds = Object.keys(mentorMessages.streakMessages)
    .map(Number)
    .sort((a, b) => b - a);
  for (const t of thresholds) {
    if (days >= t) return mentorMessages.streakMessages[t];
  }
  return `🔥 ${days} day streak! Keep it up!`;
};

/**
 * Get quiz feedback based on score percentage
 */
export const getQuizFeedback = (scorePercent) => {
  let tier;
  if (scorePercent === 100) tier = 'perfect';
  else if (scorePercent >= 80) tier = 'excellent';
  else if (scorePercent >= 60) tier = 'good';
  else if (scorePercent >= 40) tier = 'needsWork';
  else tier = 'poor';

  const msgs = mentorMessages.quizFeedback[tier];
  return msgs[Math.floor(Math.random() * msgs.length)];
};

/**
 * Personalize a message by replacing {topic} or {category} placeholders
 */
export const personalizeMessage = (message, replacements = {}) => {
  let result = message;
  for (const [key, value] of Object.entries(replacements)) {
    result = result.replace(new RegExp(`\\{${key}\\}`, 'g'), value);
  }
  return result;
};
